#!/usr/bin/env python3
"""Mechanically derive runtime constants and documentation from the only workflow graph."""
import argparse
import json
from pathlib import Path
import workflow

ROOT = Path(__file__).resolve().parents[1]


def artifacts():
    payload = json.dumps(workflow.public_graph(), ensure_ascii=False, sort_keys=True, separators=(',', ':'))
    javascript = ('/* GENERATED by tools/sync_workflow.py; edit library/workflow.json only. */\n'
                  'const FigmaFlowWorkflow = Object.freeze(' + payload + ');\n'
                  'const WorkflowState = Object.freeze(FigmaFlowWorkflow.symbols.states);\n'
                  'const WorkflowEvent = Object.freeze(FigmaFlowWorkflow.symbols.events);\n'
                  'const WorkflowGuard = Object.freeze(FigmaFlowWorkflow.symbols.guards);\n'
                  'if (typeof module !== "undefined") module.exports = {FigmaFlowWorkflow,WorkflowState,WorkflowEvent,WorkflowGuard};\n')
    documentation = ('<!-- GENERATED by tools/sync_workflow.py; edit library/workflow.json only. -->\n'
                     '# Canonical production workflow\n\nGraph SHA256: `' + workflow.graph_hash() + '`\n\n```mermaid\n' + workflow.mermaid() + '\n```\n')
    return {ROOT / 'tools/workflow-constants.js': javascript,
            ROOT / 'skills/figma-flow/references/workflow.generated.md': documentation}


def check():
    return [str(path) for path, content in artifacts().items() if not path.is_file() or path.read_text() != content]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        drift = check()
        print(json.dumps({'graph_sha256': workflow.graph_hash(), 'synchronized': not drift, 'drift': drift}))
        return 1 if drift else 0
    for path, content in artifacts().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.exists() and not path.read_text().startswith(('/* GENERATED', '<!-- GENERATED')):
            parser.exit(1, 'Refuse to overwrite a non-generated file: ' + str(path) + '\n')
        path.write_text(content)
    print(json.dumps({'graph_sha256': workflow.graph_hash(), 'generated': [str(path) for path in artifacts()]}))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
